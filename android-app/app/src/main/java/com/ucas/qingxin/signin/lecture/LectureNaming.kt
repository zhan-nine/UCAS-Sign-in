package com.ucas.qingxin.signin.lecture

/**
 * 从课程注册表的课程名里认出「这是一场具体讲座」。
 *
 * 纯字符串判定，**不触网**，因此可以拿真实注册表数据离线回归（见 `LectureNamingTest`）。
 *
 * ## 判据只有一个：期次号
 * 命中 `M1167` / `第215讲` 这类期次号 ⇒ 这是一场具体讲座。
 *
 * 注册表里同时躺着两类条目，**只有期次号能把它们分开**：
 *
 * | 形态 | 真实例子 | 数量 | 是不是一场讲座 |
 * | --- | --- | --- | --- |
 * | **场次** | `M1167雁栖湖会场：夯实科技发展的文化基础` | 一场 3 个连号 | ✅ 是 |
 * | **课程容器** | `全球地缘与中国国情专题讲座` | 同名成串 4–16 个 | ❌ 不是 |
 *
 * ## 为什么**不**用「讲座 / 讲堂」这类关键词
 * 这是一个已被实测推翻的做法，写在这里以免以后有人「顺手加回来」：
 *
 * 1. 明德讲堂的注册表条目名**根本不含任何关键词** —— 实测 `cId 64241/64242/64243`
 *    三条的名称分别是 `M1167中关村会场：…`、`M1167雁栖湖会场：…`、`M1167玉泉路会场：…`。
 *    加关键词要求会把 M1167（以及全部 163 条同类条目）**一条不漏地漏掉**，
 *    正好废掉哨兵存在的意义。
 * 2. 关键词反而会**命中容器**：`全球地缘与中国国情专题讲座`、`材料科学与工程讲座`
 *    都带「讲座」二字，却都不是具体场次 —— 也就是说关键词在本数据源上
 *    既漏真阳性、又引入假阳性，方向完全反了。
 *
 * ## 判据的实测强度
 * 对全库枚举的 6968 条有名称条目做判定：`M` 形期次号命中 **163 条**，
 * 逐条检查**全部**是明德讲堂场次（`M1118`–`M1167`），普通课程命中 **0 条**。
 * 因此这不是启发式猜测，而是有全量证据支撑的规则。
 *
 * ## 诚实的边界
 * - **只覆盖「名字里带期次号」的系列**：注册表里的艺术与人文修养系列
 *   是以课程容器形态存在的（全库 `第N讲` 命中 0 条），因此哨兵实际覆盖的是
 *   明德讲堂这类会按场次追加的系列。
 * - 某个系列若把期次号只写在页面正文、不写进课程名，哨兵认不出它。
 */
internal object LectureNaming {

    /**
     * 期次号。
     *
     * 两种形态都要认，且**「第」必须可选** —— 这不是为了宽松，而是真实数据如此：
     * 人文学院网站的实测标题是 `艺术与人文修养讲座系列213讲：科学、艺术、人生`
     * （**没有「第」字**），与 `明德讲堂M1167预告：…` 并存。
     * 通知解析器（`LectureNoticeParser.ART_SESSION`）早已按「第可选」处理，
     * 这里对齐才能让同一条内容在两处（通知 / 注册表）得到同样的期次号。
     *
     * 放宽「第」是实测过误报的：对注册表全库 6968 条有名称条目做判定，
     * 严格形态命中 163 条、放宽后仍是 **163 条**，**新增 0 条** ——
     * 也就是说它只覆盖了真实存在的形态，没有引入任何容器或普通课程。
     *
     * 另有两道边界：
     * - `(?<![A-Za-z])`：避免吃掉英文编号里的 `M` + 数字（如 `csM1234`）；
     * - `(?!\d)`：避免只取到长数字的前几位（`M11671` 不能读成 `M1167`）。
     */
    private val SESSION = Regex("""(?<![A-Za-z])M(\d{3,4})(?!\d)|第?\s*(\d{1,3})\s*讲""")

    /**
     * 抽出期次号标签；不是「一场具体讲座」时返回 `null`。
     *
     * 标签规范化成 `M1167` / `第215讲` 两种形态，用于「这一场是否已经报过」的去重。
     * 不再额外解析数字用于比较大小：期次号只在同一系列内可比，
     * 跨系列的 `M1167` 与 `第215讲` 比大小没有意义。
     */
    fun sessionLabel(courseName: String): String? {
        val match = SESSION.find(courseName) ?: return null
        val mingde = match.groupValues[1]
        if (mingde.isNotEmpty()) return "M$mingde"
        val numbered = match.groupValues[2]
        return if (numbered.isNotEmpty()) "第${numbered}讲" else null
    }

    /**
     * 该课程名是否属于「一场具体讲座」。
     *
     * 就是「有没有期次号」，单独成方法只是为了让调用点读起来是它所问的问题
     * （也让以后调整判据时只有一处要改）。
     */
    fun isLectureSession(courseName: String): Boolean = sessionLabel(courseName) != null
}
